-- Preserve predictions as they were available at fixed pre-match horizons.
BEGIN;

CREATE TABLE IF NOT EXISTS public.prediction_horizon_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_prediction_id BIGINT NOT NULL
        REFERENCES public.predictions(id) ON DELETE RESTRICT,
    match_id INTEGER NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
    horizon_key TEXT NOT NULL CHECK (horizon_key IN ('24h', '6h', '20m')),
    model_version TEXT NOT NULL,
    prob_home_win NUMERIC NOT NULL CHECK (prob_home_win BETWEEN 0 AND 1),
    prob_draw NUMERIC NOT NULL CHECK (prob_draw BETWEEN 0 AND 1),
    prob_away_win NUMERIC NOT NULL CHECK (prob_away_win BETWEEN 0 AND 1),
    prob_over_2_5 NUMERIC CHECK (
        prob_over_2_5 IS NULL OR prob_over_2_5 BETWEEN 0 AND 1
    ),
    prob_btts NUMERIC CHECK (prob_btts IS NULL OR prob_btts BETWEEN 0 AND 1),
    market_probabilities JSONB NOT NULL DEFAULT '{}'::JSONB,
    source_predicted_at TIMESTAMPTZ NOT NULL,
    captured_at TIMESTAMPTZ NOT NULL,
    lead_minutes NUMERIC NOT NULL CHECK (lead_minutes >= 0),
    prediction_age_minutes NUMERIC NOT NULL CHECK (prediction_age_minutes >= 0),
    CONSTRAINT horizon_snapshot_valid_1x2_sum CHECK (
        ABS((prob_home_win + prob_draw + prob_away_win) - 1) <= 0.001
    ),
    UNIQUE (match_id, horizon_key)
);

CREATE INDEX IF NOT EXISTS idx_prediction_horizon_snapshots_horizon
    ON public.prediction_horizon_snapshots(horizon_key, captured_at DESC);

ALTER TABLE public.prediction_horizon_snapshots ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.prediction_horizon_snapshots FROM anon, authenticated;
GRANT SELECT, INSERT ON public.prediction_horizon_snapshots TO service_role;
GRANT USAGE, SELECT ON SEQUENCE
    public.prediction_horizon_snapshots_id_seq TO service_role;

COMMIT;
