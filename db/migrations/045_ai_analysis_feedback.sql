-- Collect anonymous, structured usefulness feedback for exact AI comment versions.
BEGIN;

CREATE TABLE public.ai_analysis_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
    model_version TEXT NOT NULL CHECK (char_length(model_version) BETWEEN 1 AND 64),
    analysis_hash TEXT NOT NULL CHECK (analysis_hash ~ '^[0-9a-f]{64}$'),
    session_id UUID NOT NULL,
    helpful BOOLEAN NOT NULL,
    issue_codes TEXT[] NOT NULL DEFAULT '{}'
        CHECK (cardinality(issue_codes) <= 4 AND issue_codes <@ ARRAY[
            'generic', 'missing_data', 'unclear_reasoning', 'data_error'
        ]::TEXT[]),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (match_id, model_version, analysis_hash, session_id)
);

CREATE INDEX idx_ai_analysis_feedback_created
    ON public.ai_analysis_feedback(created_at DESC);

ALTER TABLE public.ai_analysis_feedback ENABLE ROW LEVEL SECURITY;

CREATE POLICY ai_analysis_feedback_insert
    ON public.ai_analysis_feedback
    FOR INSERT TO anon, authenticated
    WITH CHECK (true);

REVOKE ALL ON TABLE public.ai_analysis_feedback FROM PUBLIC, anon, authenticated;
GRANT INSERT ON TABLE public.ai_analysis_feedback TO anon, authenticated;
GRANT USAGE ON SEQUENCE public.ai_analysis_feedback_id_seq TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.ai_analysis_feedback TO service_role;

COMMIT;
