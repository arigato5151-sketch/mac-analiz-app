BEGIN;
CREATE TABLE IF NOT EXISTS public.daily_coupon_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_date DATE NOT NULL,
    coupon_type TEXT NOT NULL CHECK (coupon_type IN ('low_risk', 'balanced', 'high_odds')),
    selections JSONB NOT NULL,
    total_odds NUMERIC(12,4) NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'won', 'lost')),
    result_message_sent_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    settled_at TIMESTAMPTZ,
    UNIQUE (coupon_date, coupon_type)
);
CREATE INDEX IF NOT EXISTS idx_daily_coupon_runs_pending ON public.daily_coupon_runs(status, coupon_date);
GRANT SELECT, INSERT, UPDATE ON public.daily_coupon_runs TO service_role;
REVOKE ALL ON public.daily_coupon_runs FROM anon, authenticated;
COMMIT;
