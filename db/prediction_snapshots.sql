-- Immutable audit trail for the exact prediction delivered before kickoff.
BEGIN;

CREATE TABLE IF NOT EXISTS public.prediction_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_prediction_id BIGINT NOT NULL REFERENCES public.predictions(id) ON DELETE RESTRICT,
    match_id INTEGER NOT NULL REFERENCES public.matches(id) ON DELETE CASCADE,
    snapshot_type TEXT NOT NULL CHECK (snapshot_type IN ('pre_match_60m')),
    model_version TEXT NOT NULL,
    prob_home_win NUMERIC NOT NULL CHECK (prob_home_win BETWEEN 0 AND 1),
    prob_draw NUMERIC NOT NULL CHECK (prob_draw BETWEEN 0 AND 1),
    prob_away_win NUMERIC NOT NULL CHECK (prob_away_win BETWEEN 0 AND 1),
    prob_over_2_5 NUMERIC CHECK (prob_over_2_5 IS NULL OR prob_over_2_5 BETWEEN 0 AND 1),
    prob_btts NUMERIC CHECK (prob_btts IS NULL OR prob_btts BETWEEN 0 AND 1),
    source_predicted_at TIMESTAMPTZ NOT NULL,
    context JSONB NOT NULL DEFAULT '{}'::JSONB,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT snapshot_valid_1x2_probability_sum CHECK (ABS((prob_home_win + prob_draw + prob_away_win) - 1) <= 0.001),
    UNIQUE (match_id, snapshot_type)
);

ALTER TABLE public.prediction_performance
    ADD COLUMN IF NOT EXISTS snapshot_id BIGINT UNIQUE
    REFERENCES public.prediction_snapshots(id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS idx_prediction_snapshots_match
    ON public.prediction_snapshots(match_id, captured_at DESC);

GRANT SELECT, INSERT ON public.prediction_snapshots TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;

COMMIT;
